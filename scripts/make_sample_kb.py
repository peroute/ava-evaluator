"""Generate a small sample knowledge base as .docx files.

The real knowledge base is TTU's own Word documents. These stand-ins exist so
the pipeline can be run and tested end to end without them, and they are
generated by script rather than committed as binaries so the content stays
reviewable in a diff.

They are deliberately shaped like the real thing in the ways that matter:
heading hierarchy, a policy table (the content a naive extractor drops), and a
general university-wide rule sitting alongside a program-specific override.

Run:  python scripts/make_sample_kb.py
"""

from __future__ import annotations

from pathlib import Path

from docx import Document

KB_DIR = Path(__file__).resolve().parent.parent / "sample_data" / "kb"


def build_admissions() -> Document:
    """Admissions policy, including the GPA table."""
    doc = Document()
    doc.add_heading("Undergraduate Admissions", level=1)

    doc.add_heading("2.1 Minimum Grade Point Average", level=2)
    doc.add_paragraph(
        "Applicants to Texas Tech University Online undergraduate programs must present a "
        "minimum cumulative grade point average of 2.0 on a 4.0 scale from the most recently "
        "attended institution. Applicants below this threshold may be considered for "
        "provisional admission at the discretion of the admitting college."
    )

    doc.add_heading("2.2 Program Specific Requirements", level=2)
    doc.add_paragraph(
        "Where a program states a requirement different from the university minimum, the "
        "program requirement applies."
    )

    # The table is the point of this document. A naive python-docx extractor
    # that iterates document.paragraphs returns none of the rows below.
    table = doc.add_table(rows=1, cols=3)
    table.style = "Table Grid"
    headers = table.rows[0].cells
    headers[0].text = "Program"
    headers[1].text = "Minimum GPA"
    headers[2].text = "Transferable Credit Hours Required"

    rows = [
        ("Online BBA in General Business", "2.0", "30"),
        ("Online BS in Computer Science", "2.75", "30"),
        ("Online BA in Psychology", "2.0", "24"),
    ]
    for program, gpa, hours in rows:
        cells = table.add_row().cells
        cells[0].text = program
        cells[1].text = gpa
        cells[2].text = hours

    doc.add_heading("2.3 Official Transcripts", level=2)
    doc.add_paragraph(
        "All undergraduate applicants must submit official transcripts from every institution "
        "previously attended, regardless of whether credit was earned. Transcripts must be "
        "sent directly from the issuing institution to the Office of Admissions."
    )

    return doc


def build_programs() -> Document:
    """Program formats and delivery."""
    doc = Document()
    doc.add_heading("Online Program Formats", level=1)

    doc.add_heading("Bachelor of Business Administration in General Business", level=2)
    doc.add_paragraph(
        "The Online Bachelor of Business Administration in General Business is delivered fully "
        "asynchronously, with no scheduled live class meetings. Coursework is completed on the "
        "student's own schedule within weekly deadlines."
    )
    doc.add_paragraph(
        "The program requires 120 total credit hours for graduation, of which at least 30 must "
        "be completed through Texas Tech University."
    )

    doc.add_heading("Bachelor of Science in Computer Science", level=2)
    doc.add_paragraph(
        "The Online Bachelor of Science in Computer Science includes two synchronous lab "
        "sessions per week, held in the evening to accommodate working students. All remaining "
        "coursework is asynchronous."
    )

    doc.add_heading("Bachelor of Arts in Psychology", level=2)
    doc.add_paragraph(
        "The Online Bachelor of Arts in Psychology is delivered fully asynchronously and "
        "requires 120 total credit hours for graduation."
    )

    return doc


def build_tuition() -> Document:
    """Tuition, aid, and deadlines."""
    doc = Document()
    doc.add_heading("Tuition and Financial Aid", level=1)

    doc.add_heading("Application Deadlines", level=2)
    table = doc.add_table(rows=1, cols=3)
    table.style = "Table Grid"
    headers = table.rows[0].cells
    headers[0].text = "Term"
    headers[1].text = "Application Deadline"
    headers[2].text = "Priority Financial Aid Deadline"

    rows = [
        ("Fall", "July 1", "March 15"),
        ("Spring", "November 1", "October 1"),
        ("Summer", "April 1", "March 1"),
    ]
    for term, application, aid in rows:
        cells = table.add_row().cells
        cells[0].text = term
        cells[1].text = application
        cells[2].text = aid

    doc.add_heading("FAFSA", level=2)
    doc.add_paragraph(
        "Students must submit the Free Application for Federal Student Aid using Texas Tech "
        "University school code 003644. Online students are eligible for federal aid on the "
        "same basis as on-campus students."
    )

    doc.add_heading("Tuition Rates", level=2)
    doc.add_paragraph(
        "Online undergraduate tuition is charged at a flat rate per credit hour regardless of "
        "residency. Rates are published annually by Student Business Services."
    )

    return doc


def main() -> None:
    """Write the sample documents, overwriting any previous run."""
    KB_DIR.mkdir(parents=True, exist_ok=True)

    documents = {
        "admissions_requirements.docx": build_admissions(),
        "online_programs.docx": build_programs(),
        "tuition_and_aid.docx": build_tuition(),
    }

    for name, document in documents.items():
        path = KB_DIR / name
        document.save(str(path))
        print(f"wrote {path}")

    print(f"\n{len(documents)} sample documents written to {KB_DIR}")


if __name__ == "__main__":
    main()
