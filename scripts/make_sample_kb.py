"""Generate a small sample knowledge base shaped like TTU's real document.

The real knowledge base is TTU's ``online.docx``, which is not committed. This
stand-in exists so the pipeline can be run and tested end to end without it,
and it is generated by script rather than committed as a binary so the content
stays reviewable in a diff.

It copies the real document's conventions, because the parser depends on them:

* bold ``If asked questions about X, answer with`` markers opening each topic
* scaffold labels (Introduction, Question, Answer) and a Table of Contents
  whose lines repeat the questions answered below it
* a catalog topic ("Bachelor's Degrees") whose TOC lists the program pages,
  including one program with no page
* program pages with an overview, prerequisites and nested deadline labels
* a policy table inside an answer (the content a naive extractor drops), and a
  general university-wide rule alongside a program-specific override

The facts match what the sample transcripts claim, so the demo produces
supported, contradicted and not-found verdicts.

Run:  python scripts/make_sample_kb.py
"""

from __future__ import annotations

from pathlib import Path

from docx import Document

KB_DIR = Path(__file__).resolve().parent.parent / "sample_data" / "kb"
KB_FILE = KB_DIR / "sample_online.docx"

# Earlier versions generated one file per topic. They are removed so nobody
# indexes a stale copy by pointing AVA_KB_FILE at one of them.
_LEGACY_FILES = ("admissions_requirements.docx", "online_programs.docx", "tuition_and_aid.docx")


def _bold(doc: Document, text: str) -> None:
    doc.add_paragraph().add_run(text).bold = True


def _text(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def _item(doc: Document, text: str) -> None:
    doc.add_paragraph(text, style="List Paragraph")


def _topic(doc: Document, name: str) -> None:
    _bold(doc, f"If asked questions about {name}, answer with")


def _table(doc: Document, header: tuple[str, ...], rows: list[tuple[str, ...]]) -> None:
    table = doc.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    for cell, value in zip(table.rows[0].cells, header):
        cell.text = value
    for row in rows:
        for cell, value in zip(table.add_row().cells, row):
            cell.text = value


def _deadlines(doc: Document) -> None:
    """The deadline block every program page repeats word for word."""
    _bold(doc, "Application Deadlines")
    _bold(doc, "Late Fall")
    _text(doc, "Application Deadline - October 10, 2026")
    _text(doc, "Classes Begin - October 19, 2026")
    _bold(doc, "Early Spring")
    _text(doc, "Application Deadline - January 1, 2027")
    _text(doc, "Classes Begin - January 8, 2027")
    _text(doc, "Apply (opens in new tab)")


def build() -> Document:
    """Build the whole sample knowledge base as one document."""
    doc = Document()

    _topic(doc, "Undergraduate Admissions")
    _bold(doc, "Introduction")
    _text(doc, "Below you will find the admission questions Texas Tech Online is asked most often.")
    _bold(doc, "Table of Contents")
    _text(doc, "What GPA do I need to be admitted?")
    _text(doc, "Do programs set their own requirements?")
    _text(doc, "Do I need to send official transcripts?")

    _bold(doc, "What GPA do I need to be admitted?")
    _text(
        doc,
        "Applicants to Texas Tech University Online undergraduate programs must present a "
        "minimum cumulative grade point average of 2.0 on a 4.0 scale from the most recently "
        "attended institution. Applicants below this threshold may be considered for "
        "provisional admission at the discretion of the admitting college.",
    )

    _bold(doc, "Do programs set their own requirements?")
    _text(
        doc,
        "Yes. Where a program states a requirement different from the university minimum, "
        "the program requirement applies.",
    )
    # A sub-label inside an answer: it must stay with the question above it.
    _bold(doc, "Program Requirements")
    _table(
        doc,
        ("Program", "Minimum GPA", "Transferable Credit Hours Required"),
        [
            ("Online BBA in General Business", "2.0", "30"),
            ("Online BS in Computer Science", "2.75", "30"),
            ("Online BA in Psychology", "2.0", "24"),
        ],
    )

    _bold(doc, "Do I need to send official transcripts?")
    _text(
        doc,
        "All undergraduate applicants must submit official transcripts from every institution "
        "previously attended, regardless of whether credit was earned. Transcripts must be "
        "sent directly from the issuing institution to the Office of Admissions.",
    )

    _topic(doc, "Bachelor's Degrees")
    _bold(doc, "Introduction")
    _text(doc, "Texas Tech Online offers the following bachelor's degrees:")
    _bold(doc, "Table of Contents")
    _text(doc, "Online Bachelor of Business Administration in General Business")
    _text(doc, "Online Bachelor of Science in Computer Science")
    _text(doc, "Online Bachelor of Arts in Psychology")
    _text(doc, "Online Bachelor of Arts in History")  # listed, but has no page below

    _topic(doc, "the Online Bachelor of Business Administration in General Business")
    _text(
        doc,
        "The Online Bachelor of Business Administration in General Business is delivered fully "
        "asynchronously, with no scheduled live class meetings. Coursework is completed on the "
        "student's own schedule within weekly deadlines.",
    )
    _text(
        doc,
        "The program requires 120 total credit hours for graduation, of which at least 30 must "
        "be completed through Texas Tech University.",
    )
    _bold(doc, "Prerequisites")
    _item(doc, "High school diploma or equivalent")
    _item(doc, "Degree and Course Details (opens in new tab)")
    _deadlines(doc)

    _topic(doc, "the Online Bachelor of Science in Computer Science")
    _text(
        doc,
        "The Online Bachelor of Science in Computer Science includes two synchronous lab "
        "sessions per week, held in the evening to accommodate working students. All remaining "
        "coursework is asynchronous.",
    )
    _deadlines(doc)

    _topic(doc, "the Online Bachelor of Arts in Psychology")
    _text(
        doc,
        "The Online Bachelor of Arts in Psychology is delivered fully asynchronously and "
        "requires 120 total credit hours for graduation.",
    )
    _deadlines(doc)

    _topic(doc, "Tuition and Financial Aid")
    _bold(doc, "Question")
    _bold(
        doc,
        "Below are some of the Frequently Asked Questions (FAQ's) that we receive about "
        "tuition and financial aid",
    )
    _bold(doc, "Answer")
    _bold(doc, "Table of Contents")
    _text(doc, "When are the application and financial aid deadlines?")
    _text(doc, "What is the FAFSA school code?")
    _text(doc, "How is online tuition charged?")

    _bold(doc, "When are the application and financial aid deadlines?")
    _text(doc, "Deadlines depend on the term:")
    _table(
        doc,
        ("Term", "Application Deadline", "Priority Financial Aid Deadline"),
        [
            ("Fall", "July 1", "March 15"),
            ("Spring", "November 1", "October 1"),
            ("Summer", "April 1", "March 1"),
        ],
    )

    _bold(doc, "What is the FAFSA school code?")
    _text(
        doc,
        "Students must submit the Free Application for Federal Student Aid using Texas Tech "
        "University school code 003644. Online students are eligible for federal aid on the "
        "same basis as on-campus students.",
    )

    _bold(doc, "How is online tuition charged?")
    _text(
        doc,
        "Online undergraduate tuition is charged at a flat rate per credit hour regardless of "
        "residency. Rates are published annually by Student Business Services.",
    )

    return doc


def main() -> None:
    """Write the sample knowledge base, overwriting any previous run."""
    KB_DIR.mkdir(parents=True, exist_ok=True)

    for name in _LEGACY_FILES:
        legacy = KB_DIR / name
        if legacy.exists():
            legacy.unlink()
            print(f"removed legacy {legacy}")

    build().save(str(KB_FILE))
    print(f"wrote {KB_FILE}")


if __name__ == "__main__":
    main()
